import { Schema, model } from 'mongoose';

const checklistItemSchema = new Schema(
  {
    number: { type: Number },
    category: { type: String, trim: true },
    name: { type: String, required: true, trim: true },
    required: { type: Boolean, default: true },
    received: { type: Boolean, default: false },
    receivedAt: { type: Date },
    custodyStatus: { type: String, enum: ['O', 'C', 'A'] },
    remarks: { type: String, trim: true },
  },
  { _id: false },
);

const studentWorkflowSchema = new Schema(
  {
    studentId: { type: Schema.Types.ObjectId, ref: 'Student', required: true, unique: true },
    documentChecklist: { type: [checklistItemSchema], default: [] },
    clientDeclaration: {
      accepted: { type: Boolean, default: false },
      signedAt: { type: Date },
      notes: { type: String, trim: true },
      passportOrNid: { type: String, trim: true },
      date: { type: Date },
      statements: { type: [Boolean], default: [] },
      dataConsents: { type: [Boolean], default: [] },
      guardianName: { type: String, trim: true },
      guardianRelationship: { type: String, trim: true },
      guardianDate: { type: Date },
      witnessNameDesignation: { type: String, trim: true },
    },
    termsConditions: { accepted: { type: Boolean, default: false }, acceptedAt: { type: Date }, notes: { type: String, trim: true } },
    moneyReceipt: {
      clientCopy: { type: String, trim: true },
      officeCopy: { type: String, trim: true },
      receiptNumber: { type: String, trim: true },
      date: { type: Date },
      receivedWithThanksFrom: { type: String, trim: true },
      amountInWords: { type: String, trim: true },
      amount: { type: Number, min: 0 },
      paymentMode: { type: String, trim: true },
      paymentReceivedFor: { type: [String], default: [] },
      cashChequeRef: { type: String, trim: true },
      bankWallet: { type: String, trim: true },
      totalFee: { type: Number, min: 0 },
      paidToDate: { type: Number, min: 0 },
      thisPayment: { type: Number, min: 0 },
      balanceDue: { type: Number, min: 0 },
      currency: { type: String, uppercase: true },
      receivedAt: { type: Date },
      notes: { type: String, trim: true },
    },
    officialInvoice: {
      invoiceNumber: { type: String, trim: true },
      amount: { type: Number, min: 0 },
      currency: { type: String, uppercase: true },
      issuedAt: { type: Date },
      dueAt: { type: Date },
      clientAddress: { type: String, trim: true },
      serviceType: { type: String, trim: true },
      amountInWords: { type: String, trim: true },
      items: {
        type: [{
          description: { type: String, trim: true },
          quantity: { type: Number, min: 0 },
          unitPrice: { type: Number, min: 0 },
          amount: { type: Number, min: 0 },
        }],
        default: [],
      },
      subtotal: { type: Number, min: 0 },
      discount: { type: Number, min: 0 },
      tax: { type: Number, min: 0 },
      total: { type: Number, min: 0 },
      amountPaid: { type: Number, min: 0 },
      balanceDue: { type: Number, min: 0 },
      bankName: { type: String, trim: true },
      accountName: { type: String, trim: true },
      accountNumber: { type: String, trim: true },
      branchRouting: { type: String, trim: true },
      bKashNagadOther: { type: String, trim: true },
      paymentReference: { type: String, trim: true },
      notes: { type: String, trim: true },
    },
    refundCancellationPolicy: { acknowledged: { type: Boolean, default: false }, notes: { type: String, trim: true }, clientName: { type: String, trim: true }, clientId: { type: String, trim: true }, date: { type: Date } },
    updatedBy: { type: Schema.Types.ObjectId, ref: 'User', required: true },
  },
  { timestamps: true },
);

export const StudentWorkflow = model('StudentWorkflow', studentWorkflowSchema);
